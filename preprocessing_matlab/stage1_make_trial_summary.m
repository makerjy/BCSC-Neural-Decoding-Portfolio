function summary_table = stage1_make_trial_summary(info_table)
    [group_id, task, tms, target, category] = findgroups( ...
        info_table.TaskCanonical, ...
        info_table.TMSCanonical, ...
        info_table.TargetCanonical, ...
        info_table.CategoryCanonical);

    trial_count = splitapply(@numel, info_table.csv_row, group_id);

    summary_table = table( ...
        task, tms, target, category, trial_count, ...
        'VariableNames', { ...
        'Task', 'TMS', 'TMStarget', 'Category', 'TrialCount'});

    summary_table = sortrows(summary_table, ...
        {'Task', 'TMS', 'TMStarget', 'Category'});
end
