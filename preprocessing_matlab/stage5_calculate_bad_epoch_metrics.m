function qc_table = stage5_calculate_bad_epoch_metrics(EEG)

    n_epochs = EEG.trials;

    original_epoch = (1:n_epochs)';

    event_label = strings(n_epochs, 1);
    task = strings(n_epochs, 1);
    tms_status = strings(n_epochs, 1);
    target = strings(n_epochs, 1);
    category = strings(n_epochs, 1);

    max_centered_abs_uV = zeros(n_epochs, 1);
    max_peak_to_peak_uV = zeros(n_epochs, 1);
    median_channel_rms_uV = zeros(n_epochs, 1);
    max_sample_step_uV = zeros(n_epochs, 1);

    n_channels_centered_abs_gt_100 = zeros(n_epochs, 1);
    n_channels_peak_to_peak_gt_200 = zeros(n_epochs, 1);

    for epoch_index = 1:n_epochs

        epoch_data = double( ...
            EEG.data(:, :, epoch_index));

        % Remove each channel's within-epoch median only for QC metric
        % calculation. EEG.data itself is not modified.
        %
        % This prevents a constant offset from dominating the maximum
        % amplitude measurement.

        channel_median = median(epoch_data, 2);

        centered_epoch_data = ...
            epoch_data - channel_median;

        channel_centered_abs = ...
            max(abs(centered_epoch_data), [], 2);

        channel_peak_to_peak = ...
            max(epoch_data, [], 2) - ...
            min(epoch_data, [], 2);

        channel_rms = sqrt( ...
            mean(centered_epoch_data .^ 2, 2));

        if EEG.pnts > 1

            channel_sample_step = max( ...
                abs(diff(epoch_data, 1, 2)), ...
                [], ...
                2);

        else

            channel_sample_step = ...
                zeros(EEG.nbchan, 1);
        end

        max_centered_abs_uV(epoch_index) = ...
            max(channel_centered_abs);

        max_peak_to_peak_uV(epoch_index) = ...
            max(channel_peak_to_peak);

        median_channel_rms_uV(epoch_index) = ...
            median(channel_rms);

        max_sample_step_uV(epoch_index) = ...
            max(channel_sample_step);

        n_channels_centered_abs_gt_100(epoch_index) = ...
            sum(channel_centered_abs > 100);

        n_channels_peak_to_peak_gt_200(epoch_index) = ...
            sum(channel_peak_to_peak > 200);

        current_event_label = ...
            get_stim1_event_label(EEG, epoch_index);

        event_label(epoch_index) = ...
            current_event_label;

        label_parts = split( ...
            current_event_label, ...
            "/");

        if numel(label_parts) >= 4

            task(epoch_index) = label_parts(1);
            tms_status(epoch_index) = label_parts(2);
            target(epoch_index) = label_parts(3);
            category(epoch_index) = label_parts(4);

        else

            task(epoch_index) = "unknown";
            tms_status(epoch_index) = "unknown";
            target(epoch_index) = "unknown";
            category(epoch_index) = "unknown";
        end
    end

    qc_table = table( ...
        original_epoch, ...
        event_label, ...
        task, ...
        tms_status, ...
        target, ...
        category, ...
        max_centered_abs_uV, ...
        max_peak_to_peak_uV, ...
        median_channel_rms_uV, ...
        max_sample_step_uV, ...
        n_channels_centered_abs_gt_100, ...
        n_channels_peak_to_peak_gt_200, ...
        'VariableNames', { ...
            'OriginalEpoch', ...
            'EventLabel', ...
            'Task', ...
            'TMSStatus', ...
            'Target', ...
            'Category', ...
            'MaxCenteredAbs_uV', ...
            'MaxPeakToPeak_uV', ...
            'MedianChannelRMS_uV', ...
            'MaxSampleStep_uV', ...
            'NChannelsCenteredAbsAbove100uV', ...
            'NChannelsPeakToPeakAbove200uV'});
end


function event_label = get_stim1_event_label(EEG, epoch_index)

    event_label = "";

    epoch_event_type = ...
        EEG.epoch(epoch_index).eventtype;

    if ~iscell(epoch_event_type)
        epoch_event_type = {epoch_event_type};
    end

    event_type_strings = ...
        string(epoch_event_type);

    anchor_index = find( ...
        endsWith( ...
            lower(event_type_strings), ...
            "/stim_1"), ...
        1, ...
        'first');

    if isempty(anchor_index)

        anchor_index = find( ...
            contains( ...
                lower(event_type_strings), ...
                "stim_1"), ...
            1, ...
            'first');
    end

    if isempty(anchor_index)

        warning( ...
            'No stim_1 event was found in epoch %d.', ...
            epoch_index);

        event_label = "unknown";

    else

        event_label = ...
            event_type_strings(anchor_index);
    end
end


