function normalized_label = stage1_normalize_auxiliary_channel_label(channel_label)

    normalized_label = upper(strtrim(char(channel_label)));

    % Remove spaces, underscores and hyphens.
    normalized_label = regexprep( ...
        normalized_label, ...
        '[\s_\-]', ...
        '');

    % Normalize BIP03 or BIP003 to BIP3.
    bip_match = regexp( ...
        normalized_label, ...
        '^BIP0*([0-9]+)$', ...
        'tokens', ...
        'once');

    if ~isempty(bip_match)

        bip_number = str2double(bip_match{1});

        normalized_label = sprintf( ...
            'BIP%d', ...
            bip_number);
    end

end