
function token = stage8_make_file_token(value)
% MAKE_FILE_TOKEN
%
% Converts a task, condition, or category string into a safe filename
% component.

    token = lower(char(string(value)));

    token = regexprep( ...
        token, ...
        '[^a-zA-Z0-9_-]+', ...
        '_');

    token = regexprep( ...
        token, ...
        '_+', ...
        '_');

    token = regexprep( ...
        token, ...
        '^_+', ...
        '');

    token = regexprep( ...
        token, ...
        '_+$', ...
        '');

    if isempty(token)
        error('An empty filename token was generated.');
    end
end